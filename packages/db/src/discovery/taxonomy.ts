/** All discovery slugs in card order (primary assignment candidates). */
export const DISCOVERY_CATEGORY_SLUGS: readonly string[] = DISCOVERY_CATEGORIES.map(
  (category) => category.slug,
);

export function getDiscoveryCategory(slug: string): DiscoveryCategory | undefined {
  return DISCOVERY_CATEGORIES.find((category) => category.slug === slug);
}

export function isDiscoveryCategorySlug(slug: string): boolean {
  return DISCOVERY_CATEGORY_SLUGS.includes(slug);
}
