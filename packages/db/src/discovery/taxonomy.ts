/**
 * Discovery taxonomy: the food/CPG supplier categories behind the
 * category-first discovery surfaces.
 *
 * This is deliberately a NEW module, separate from the nine-family packaging
 * taxonomy (src/taxonomy) — that one classifies packaging listings for search
 * and RFQs; this one classifies real supplier records from the Platform Ready
 * directory. They share no slugs and no code paths.
 *
 * Keyword rules were scored against the real workbook (7,658 records): each
 * keyword anchors a category, and the import report is the tuning dial —
 * tuning is a data edit here, never a classifier code change.
 */

export interface DiscoveryCategory {
  /** URL key, e.g. "dairy" → /categories/dairy. */
  slug: string;
  /** Card and page heading, e.g. "Dairy & Cheese". */
  name: string;
  /** One-line card copy. */
  description: string;
  /** Keyword anchors, matched case-insensitively on word boundaries. */
  keywords: string[];
  /** Committed artwork path, e.g. "/discovery/dairy.jpg". */
  image: string;
}

